# ============================================================
# Nutrient time-series reconstruction
# ============================================================

nutrients <- c("NO3", "NH4", "SRP", "SIO2", "NO2")

NUT_38A_TS_final <- map_dfr(nutrients, function(nut){
  
  sampler_nut <- sampler_ts %>%
    select(D_DATE, value = all_of(nut)) %>%
    filter(!is.na(value))
  
  ctd_nut <- ctd_ts %>%
    select(D_DATE, value = all_of(nut))
  
  climatology <- sampler_nut %>%
    mutate(doy = yday(D_DATE)) %>%
    group_by(doy) %>%
    summarise(
      clim = mean(value, na.rm = TRUE),
      .groups = "drop"
    )
  
  overlap <- sampler_nut %>%
    inner_join(
      ctd_nut,
      by = "D_DATE",
      suffix = c("_sampler", "_ctd")
    )
  
  has_bias_model <- nrow(overlap) >= 3
  
  if (has_bias_model){
    
    bias_model <- lm(
      value_sampler ~ value_ctd,
      data = overlap
    )
    
    ctd_cal <- ctd_nut %>%
      rename(value_ctd = value) %>%
      mutate(
        value_cal =
          predict(bias_model, newdata = .)
      )
    
  } else {
    
    ctd_cal <- ctd_nut %>%
      rename(value_ctd = value) %>%
      mutate(value_cal = NA_real_)
  }
  
  daily_post_2023 <- tibble(
    D_DATE = seq(
      as.Date("2023-01-01"),
      as.Date("2025-12-31"),
      by = "day"
    )
  ) %>%
    mutate(doy = yday(D_DATE))
  
  post_2023 <- daily_post_2023 %>%
    left_join(ctd_cal, by = "D_DATE") %>%
    left_join(climatology, by = "doy") %>%
    mutate(
      value_final =
        if_else(!is.na(value_cal),
                value_cal,
                clim),
      source = case_when(
        !is.na(value_cal) &
          has_bias_model ~
          "ctd_bias_corrected",
        TRUE ~
          "climatology"
      )
    ) %>%
    select(
      D_DATE,
      value_final,
      source
    )
  
  pre_2023 <- sampler_nut %>%
    filter(D_DATE < as.Date("2023-01-01")) %>%
    transmute(
      D_DATE,
      value_final = value,
      source = "sampler"
    )
  
  bind_rows(
    pre_2023,
    post_2023
  ) %>%
    arrange(D_DATE) %>%
    mutate(nutrient = nut)
})

# ============================================================
# Observational nutrient records only
# ============================================================

obs_ts <- NUT_38A_TS_final %>%
  filter(
    source %in%
      c("sampler",
        "ctd_bias_corrected")
  ) %>%
  mutate(
    year = year(D_DATE),
    doy = yday(D_DATE),
    month = month(D_DATE)
  )

# ============================================================
# Nutrient drawdown timing
# ============================================================

winter_mean <- obs_ts %>%
  filter(month %in% c(1,2)) %>%
  group_by(year, nutrient) %>%
  summarise(
    winter_mean =
      mean(value_final,
           na.rm = TRUE),
    .groups = "drop"
  )

spring_ts <- obs_ts %>%
  filter(month %in% 3:6) %>%
  left_join(
    winter_mean,
    by = c("year","nutrient")
  ) %>%
  mutate(
    threshold =
      0.75 * winter_mean
  )

drawdown_timing <- spring_ts %>%
  filter(value_final <= threshold) %>%
  group_by(year, nutrient) %>%
  summarise(
    drawdown_doy = min(doy),
    .groups = "drop"
  )

# ============================================================
# Bloom metrics
# ============================================================

Bottle_Nuts <- Bottle_Nuts %>%
  mutate(
    year = year(D_DATE),
    month = month(D_DATE)
  )

bloom_metrics <- Bottle_Nuts %>%
  filter(month %in%
           c(1,2,4,5,6)) %>%
  group_by(year) %>%
  summarise(
    winter_min_chl =
      min(CHA[month %in% c(1,2)],
          na.rm = TRUE),
    
    spring_max_chl =
      max(CHA[month %in% c(4,5,6)],
          na.rm = TRUE),
    
    .groups = "drop"
  ) %>%
  filter(year < 2026) %>%
  mutate(
    bloom_intensity =
      spring_max_chl -
      winter_min_chl
  )

# ============================================================
# Nutrient-specific ecosystem metrics
# ============================================================

build_nutrient_bloom_df <- function(nut){
  
  drawdown_timing_nut <-
    drawdown_timing %>%
    filter(nutrient == nut) %>%
    select(year,
           drawdown_doy)
  
  winter_mean_nut <- obs_ts %>%
    filter(
      nutrient == nut,
      month %in% c(1,2)
    ) %>%
    group_by(year) %>%
    summarise(
      winter_mean_nut =
        mean(value_final,
             na.rm = TRUE),
      .groups = "drop"
    )
  
  spring_min_nut <- obs_ts %>%
    filter(
      nutrient == nut,
      month %in% 3:6
    ) %>%
    group_by(year) %>%
    summarise(
      spring_min_nut =
        min(value_final,
            na.rm = TRUE),
      .groups = "drop"
    )
  
  bloom_metrics %>%
    left_join(
      winter_mean_nut,
      by = "year"
    ) %>%
    left_join(
      spring_min_nut,
      by = "year"
    ) %>%
    left_join(
      drawdown_timing_nut,
      by = "year"
    ) %>%
    mutate(
      drawdown_mag =
        winter_mean_nut -
        spring_min_nut,
      nutrient = nut
    )
}

analysis_all <- map_dfr(
  nutrients,
  build_nutrient_bloom_df
)

