  sst_hw,
  sst_cs,
  by = "year"
)

analysis_all_sst <- analysis_all %>%
  left_join(
    sst_metrics,
    by = "year"
  ) %>%
  mutate(
    thermal_stress =
      scale(hw_int_cum) -
      scale(cs_int_cum),
    
    nutrient_constraint =
      scale(drawdown_mag),
    
    thermal_background =
      scale(temp_mean)
  )

